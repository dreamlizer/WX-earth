const NAME_TZ_FALLBACKS = [
  { names: [/France|法国/i], tz: "Europe/Paris" },
  { names: [/Norway|挪威/i], tz: "Europe/Oslo" },
  { names: [/Kosovo|科索沃/i], tz: "Europe/Belgrade" },
  { names: [/Northern\s*Cyprus|北塞浦路斯/i], tz: "Asia/Nicosia" },
  { names: [/Somaliland|索马里兰/i], tz: "Africa/Mogadishu" },
]

export function getCountryOverride(f) {
  const p = f?.props || f?.properties || {}
  const codes = [
    p.ISO_A2,
    p.ISO,
    p.ISO2,
    p.CC,
    p.ISO_A3,
    p.ISO3,
    p.ADM0_A3,
    p.SOV_A3,
  ].filter(Boolean).map(v => String(v).toUpperCase())
  for (const code of codes) {
    const tz = COUNTRY_TZ_BY_CODE[code]
    if (tz) return tz
  }

  const name = (p.ADMIN || p.NAME || p.NAME_LONG || p.NAME_EN || p.NAME_ZH || '').toString()
  for (const rule of NAME_TZ_FALLBACKS) {
    if (rule.names.some(re => re.test(name))) return rule.tz
  }
  return null
}
