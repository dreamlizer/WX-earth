export const FLAG_SPRITE_ROWS = Math.ceil(Object.keys(FLAG_INDEX).length / FLAG_SPRITE_COLUMNS);
export const FLAG_SPRITE_DISPLAY_WIDTH = FLAG_SPRITE_COLUMNS * FLAG_DISPLAY_WIDTH;
export const FLAG_SPRITE_DISPLAY_HEIGHT = FLAG_SPRITE_ROWS * FLAG_DISPLAY_HEIGHT;
export function normalizeFlagCode(code) {
  const raw = String(code || '').trim().toUpperCase();
  if (!raw || raw === '-99') return '';
  if (FLAG_INDEX[raw]) return raw;
  return FLAG_CODE_ALIASES[raw] || '';
}
export function getFlagSprite(code) {
  const flagCode = normalizeFlagCode(code);
  const entry = flagCode ? FLAG_INDEX[flagCode] : null;
  if (!entry) return null;
  const col = entry.i % FLAG_SPRITE_COLUMNS;
  const row = Math.floor(entry.i / FLAG_SPRITE_COLUMNS);
  return {
    code: flagCode,
    src: FLAG_SPRITE,
    x: col * FLAG_DISPLAY_WIDTH,
    y: row * FLAG_DISPLAY_HEIGHT,
    width: FLAG_DISPLAY_WIDTH,
    height: FLAG_DISPLAY_HEIGHT,
    sheetWidth: FLAG_SPRITE_DISPLAY_WIDTH,
    sheetHeight: FLAG_SPRITE_DISPLAY_HEIGHT,
    style: `width: ${FLAG_SPRITE_DISPLAY_WIDTH}px; height: ${FLAG_SPRITE_DISPLAY_HEIGHT}px; left: -${col * FLAG_DISPLAY_WIDTH}px; top: -${row * FLAG_DISPLAY_HEIGHT}px;`
  };
}
